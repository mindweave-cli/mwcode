// Writes assets/fonts/fonts.css from the bundled font files, taking each file's character range from
// the @fontsource package it came from. The app loads its fonts from here, never from the internet.
//   node build/make-fonts-css.js
const fs = require('fs');
const path = require('path');

const nm = path.join(__dirname, '..', 'node_modules');
function rangeOf(cssFile, fileName) {
  const css = fs.readFileSync(path.join(nm, cssFile), 'utf8');
  const block = css.split('@font-face').find((b) => b.includes(fileName));
  if (!block) throw new Error(`no range for ${fileName} in ${cssFile}`);
  return /unicode-range:\s*([^;]+);/.exec(block)[1].trim();
}
const faces = [];
function face(family, file, css, { weight, style = 'normal', stretch, variable = false }) {
  faces.push(`@font-face{
  font-family:'${family}';font-style:${style};font-weight:${weight};${stretch ? `font-stretch:${stretch};` : ''}font-display:swap;
  src:url(./${file}) format('${variable ? 'woff2-variations' : 'woff2'}');
  unicode-range:${rangeOf(css, file)};
}`);
}
const F = '@fontsource-variable/fraunces/', I = '@fontsource-variable/instrument-sans/', P = '@fontsource/ibm-plex-mono/';
// Headings: Fraunces, variable (weight, optical size, softness).
face('Fraunces', 'fraunces-latin-full-normal.woff2', F + 'full.css', { weight: '100 900', variable: true });
face('Fraunces', 'fraunces-latin-ext-full-normal.woff2', F + 'full.css', { weight: '100 900', variable: true });
face('Fraunces', 'fraunces-latin-full-italic.woff2', F + 'full-italic.css', { weight: '100 900', style: 'italic', variable: true });
// Text: Instrument Sans, variable (weight, width).
face('Instrument Sans', 'instrument-sans-latin-standard-normal.woff2', I + 'standard.css', { weight: '400 700', stretch: '75% 100%', variable: true });
face('Instrument Sans', 'instrument-sans-latin-ext-standard-normal.woff2', I + 'standard.css', { weight: '400 700', stretch: '75% 100%', variable: true });
face('Instrument Sans', 'instrument-sans-latin-standard-italic.woff2', I + 'standard-italic.css', { weight: '400 700', stretch: '75% 100%', style: 'italic', variable: true });
// Code: IBM Plex Mono.
for (const w of [400, 500, 600]) {
  face('IBM Plex Mono', `ibm-plex-mono-latin-${w}-normal.woff2`, P + `${w}.css`, { weight: w });
  face('IBM Plex Mono', `ibm-plex-mono-latin-ext-${w}-normal.woff2`, P + `${w}.css`, { weight: w });
}
face('IBM Plex Mono', 'ibm-plex-mono-latin-400-italic.woff2', P + '400-italic.css', { weight: 400, style: 'italic' });

const out = `/* The app's fonts, bundled (Open Font Licence, see the LICENSE files here). Generated by
   build/make-fonts-css.js: edit that, not this. */
${faces.join('\n')}
`;
fs.writeFileSync(path.join(__dirname, '..', 'assets', 'fonts', 'fonts.css'), out);
console.log('fonts.css:', faces.length, 'faces');
